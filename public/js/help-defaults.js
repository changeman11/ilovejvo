export const DEFAULT_FAQ = `# Getting started
## What is I<3JVO?
The home of Just Volleyball Oceania: fixtures, results and player stats for our exhibition nights and tournaments, all worked out from match results.

## How do I make a profile?
Press **make profile** (or go to the Me tab) and sign in with Discord. If you already have stats under your name, you can ask to claim that profile and an admin will approve it.

## Where do I talk to everyone?
On the JVO Discord. The link is in the bottom bar and the footer.

# Clubs
## How do I join a club?
Open the club's page (Teams & players) and press **Request to join**, or wait for a manager to invite you. Invites show up under the bell at the top.

## How do I start a club?
Open the Club tab while you're a free agent and register a team. An admin approves it, then you're the manager.

## Can I play for two clubs?
No, one club at a time. To leave, ask from the Club hub and an admin approves it.

# Results and stats
## How do results get on the site?
After a match, a player from each team reports the set scores and uploads the end-of-match screenshot. When both teams agree, the score goes up straight away. Admins then read the stats from the screenshots and check them.

## My stats are wrong or missing. What do I do?
Ask an admin on Discord. They can fix the stats and link your in-game name to your profile.

## What do the stat names mean?
PTS points, SPK spikes, BLK blocks, REC receives, SET sets, AST assists, ACE aces, DIG digs. They come straight from the game's end-of-match screen.
`;

export const DEFAULT_RULES = `# Matches
- Teams are **4v4**.
- Matches are **best of 3 sets** (some, like finals, are best of 5).
- Every set is **first to 10**, and you must **win by 2**. There's no cap.

# Results
- After the match, each team reports the set scores and uploads the end-of-match screenshot from the Club hub or the match page.
- The score goes up once both teams agree. If they don't, an admin decides.
- Keep your screenshots until the result is on the site.

# Forfeits
- A team that doesn't show loses by forfeit.
- A forfeit counts as a **2–0** win for the other team, with both sets **10–0**. No player stats are recorded.

# Tables
When an event shows a table, teams get:
- **3** points for a 2–0 win
- **2** points for a 2–1 win
- **1** point for a 1–2 loss
- **0** points for a 0–2 loss

Ties are split by points, then wins, then set ratio, then point ratio, then head-to-head.

# Clubs
- One club at a time.
- Managers invite players and accept join requests. Admins approve new clubs and players leaving.
- Be good to each other. Admins can remove pictures or text that break the Discord's rules.
`;
